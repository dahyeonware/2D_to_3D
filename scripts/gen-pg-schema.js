// db/schema.sql(SQLite) + db/views.pg.sql → supabase/migrations/<ts>_init.sql (Postgres)
// 실행: node scripts/gen-pg-schema.js   (스키마를 바꾸면 새 마이그레이션 파일을 따로 추가할 것)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from '../server/src/config.js';

const src = fs.readFileSync(path.join(ROOT, 'db', 'schema.sql'), 'utf8').replace(/\r\n/g, '\n');
const views = fs.readFileSync(path.join(ROOT, 'db', 'views.pg.sql'), 'utf8').replace(/\r\n/g, '\n');

let sql = src
  .replace(/^-- KTX 장비 시각화 SQLite 스키마.*$/m, '-- KTX 장비 시각화 Postgres 스키마 (scripts/gen-pg-schema.js 로 db/schema.sql 에서 생성)')
  .replace(/\bINTEGER PRIMARY KEY\b/g, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/\bREAL\b/g, 'DOUBLE PRECISION')
  .replace(/\(datetime\('now'\)\)/g, "(to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'))");

const tables = [...sql.matchAll(/CREATE TABLE (\w+)/g)].map((m) => m[1]);
const security = `
-- ===== 보안 =====
-- 앱 서버(Vercel 함수)는 postgres 역할로 직접 접속한다. Supabase 자동 REST(PostgREST)의
-- anon/authenticated 역할로는 읽기·쓰기 모두 못 하도록 RLS를 켜고(정책 없음) 권한을 회수한다.
${tables.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n')}
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
`;

const out = `${sql}\n${views}\n${security}`;
const dir = path.join(ROOT, 'supabase', 'migrations');
fs.mkdirSync(dir, { recursive: true });
const file = path.join(dir, '20261125000000_init.sql');
fs.writeFileSync(file, out);
console.log(`생성: ${path.relative(ROOT, file)} (테이블 ${tables.length}개)`);
